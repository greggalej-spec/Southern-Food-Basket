// Regenerates the store-front scene, then writes it as app/(home)/scene.ts for the home page to inline.
// Run from the repo root: npm run scene
const fs = require('fs'), path = require('path'), { execFileSync } = require('child_process');
const here = __dirname, root = path.join(here, '..', '..');
const scene = path.join(here, 'scene.svg');
execFileSync(process.execPath, [path.join(here, 'make-scene.js'), scene], { stdio: 'inherit' });
const svg = fs.readFileSync(scene, 'utf8').trim();
if (!svg.startsWith('<svg') || !svg.includes('class="storefront')) throw new Error('scene.svg is not the storefront scene');
const out = path.join(root, 'app', '(home)', 'scene.ts');
fs.writeFileSync(out, '// Generated by tools/grand-entrance/build.js from make-scene.js (npm run scene). Do not edit by hand.\n' +
  '// Fixed markup with no user input: the home page inlines it as the camera\'s scene.\n' +
  'export const SCENE = ' + JSON.stringify(svg) + ';\n');
console.log('app/(home)/scene.ts rebuilt');
